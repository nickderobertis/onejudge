//! The Nx install's self-healing, driven for real: `scripts/node-modules.sh` run
//! by bash in a scratch copy of the workspace's package files, with stand-in
//! `bun` and `npm` first on a `PATH` that carries nothing else of theirs.
//!
//! The package managers are faked the way the rest of the suites fake the model
//! — real executables that record how they were called — so each journey is the
//! script's own behaviour: a missing install is installed, an install matching the
//! lockfile is left alone, a changed lockfile reinstalls, a missing bun is
//! installed through npm at the pinned version, and a failed or impossible
//! install stops with what went wrong and what to do.
//!
//! Unix only: the stand-ins are `#!` scripts.
#![cfg(unix)]

use std::os::unix::fs::PermissionsExt;
use std::path::{Path, PathBuf};
use std::process::{Command, Output};
use std::sync::atomic::{AtomicUsize, Ordering};

fn repo_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../..")
        .canonicalize()
        .expect("the workspace root exists")
}

fn executable(path: &Path, body: &str) {
    std::fs::write(path, format!("#!/bin/sh\n{body}")).unwrap();
    std::fs::set_permissions(path, std::fs::Permissions::from_mode(0o755)).unwrap();
}

/// A scratch workspace with the real script and package files, and a `bin/` of
/// stand-ins. `bun` installs by creating the shim the script looks for, and
/// fails instead when `BUN_FAILS` exists; every call is appended to `calls`.
struct Scratch {
    dir: PathBuf,
    bin: PathBuf,
}

impl Scratch {
    fn new() -> Self {
        static NEXT: AtomicUsize = AtomicUsize::new(0);
        let root = repo_root();
        let dir = Path::new(env!("CARGO_TARGET_TMPDIR")).join(format!(
            "node-modules-{}-{}",
            std::process::id(),
            NEXT.fetch_add(1, Ordering::SeqCst)
        ));
        let _ = std::fs::remove_dir_all(&dir);
        std::fs::create_dir_all(dir.join("scripts")).unwrap();
        for file in ["scripts/node-modules.sh", "package.json", "bun.lock"] {
            std::fs::copy(root.join(file), dir.join(file)).unwrap();
        }
        let bin = dir.join("bin");
        std::fs::create_dir_all(&bin).unwrap();
        Self { dir, bin }
    }

    fn with_bun(self) -> Self {
        executable(
            &self.bin.join("bun"),
            "echo \"bun $*\" >> calls\n\
             if [ -e BUN_FAILS ]; then echo 'error: lockfile had changes' >&2; exit 1; fi\n\
             mkdir -p node_modules/.bin && : > node_modules/.bin/nx\n",
        );
        self
    }

    fn with_npm(self) -> Self {
        let bun = self.bin.join("bun");
        executable(
            &self.bin.join("npm"),
            &format!(
                "echo \"npm $*\" >> calls\n\
                 cat > '{bun}' <<'EOF'\n#!/bin/sh\necho \"bun $*\" >> calls\nmkdir -p node_modules/.bin && : > node_modules/.bin/nx\nEOF\n\
                 chmod +x '{bun}'\n",
                bun = bun.display()
            ),
        );
        self
    }

    fn run(&self) -> Output {
        Command::new("/bin/bash")
            .current_dir(&self.dir)
            .arg("scripts/node-modules.sh")
            .env("PATH", format!("{}:/usr/bin:/bin", self.bin.display()))
            .output()
            .expect("bash runs")
    }

    fn calls(&self) -> Vec<String> {
        std::fs::read_to_string(self.dir.join("calls"))
            .unwrap_or_default()
            .lines()
            .map(str::to_owned)
            .collect()
    }
}

fn succeeded(output: &Output) {
    assert!(
        output.status.success(),
        "{}",
        String::from_utf8_lossy(&output.stderr)
    );
    assert!(
        output.stdout.is_empty(),
        "stdout is the caller's, not the installer's"
    );
}

fn refused(output: &Output, expected: &str) {
    let stderr = String::from_utf8_lossy(&output.stderr);
    assert_eq!(output.status.code(), Some(1), "{stderr}");
    assert!(stderr.contains(expected), "{expected:?} not in: {stderr}");
    assert!(stderr.contains("ACTION:"), "no next step in: {stderr}");
}

#[test]
fn a_missing_install_is_installed_and_then_left_alone_until_the_lockfile_changes() {
    let scratch = Scratch::new().with_bun();
    succeeded(&scratch.run());
    assert_eq!(scratch.calls(), ["bun install --frozen-lockfile --silent"]);
    succeeded(&scratch.run());
    assert_eq!(
        scratch.calls().len(),
        1,
        "an install matching bun.lock was redone"
    );
    let lock = scratch.dir.join("bun.lock");
    let mut text = std::fs::read_to_string(&lock).unwrap();
    text.push('\n');
    std::fs::write(&lock, text).unwrap();
    succeeded(&scratch.run());
    assert_eq!(
        scratch.calls().len(),
        2,
        "a changed bun.lock was not reinstalled"
    );
}

#[test]
fn a_missing_bun_is_installed_through_npm_at_the_pinned_version() {
    let scratch = Scratch::new().with_npm();
    succeeded(&scratch.run());
    let pinned = std::fs::read_to_string(scratch.dir.join("package.json")).unwrap();
    let version = pinned
        .split("\"packageManager\": \"bun@")
        .nth(1)
        .and_then(|rest| rest.split('"').next())
        .expect("package.json pins bun");
    assert_eq!(
        scratch.calls(),
        [
            format!("npm install --global --silent bun@{version}"),
            "bun install --frozen-lockfile --silent".to_owned(),
        ]
    );
}

#[test]
fn a_failed_or_impossible_install_stops_with_the_next_step() {
    let scratch = Scratch::new().with_bun();
    std::fs::write(scratch.dir.join("BUN_FAILS"), "").unwrap();
    refused(&scratch.run(), "'bun install --frozen-lockfile' failed");
    assert!(
        !scratch
            .dir
            .join("node_modules/.bun-lock-installed")
            .exists(),
        "a failed install was stamped as done"
    );

    let neither = Scratch::new();
    refused(
        &neither.run(),
        "bun is not installed and cannot be installed here",
    );
}
